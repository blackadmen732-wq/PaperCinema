"""SKILLS MAP: one page listing every agent skill in the project, grouped by the job it does.

Extracted from Paper Cinema's tools/build_skills.py. The groups were Python lambdas; here they are
data in aethern.json `skills.groups`, so another project can reuse the builder without editing code:
  {"title": "...", "note": "...", "prefix": ["pc-"], "suffix": ["-style"], "names": ["graphify"]}
A skill joins the FIRST group whose prefix, suffix or names match it.

    aethern skills            rewrite the map
    aethern skills --check    exit 1 if the map is out of date
"""
import os
import re

DEFAULT = {
    'dir': '.claude/skills', 'out': 'SKILLS.md', 'preamble': None,
    'marker': '<!-- generated below this line by aethern skills -->',
    'groups': [],
    'ungrouped_note': 'Add them to `skills.groups` in aethern.json when you touch them.',
    'footer': '{n} skills. Generated by `aethern skills` — do not edit below the marker.',
    'stale': '  {out} is out of date — run: aethern skills',
}


def _matcher(g):
    pre, suf, names = tuple(g.get('prefix', [])), tuple(g.get('suffix', [])), set(g.get('names', []))
    return lambda n: (bool(pre) and n.startswith(pre)) or (bool(suf) and n.endswith(suf)) or n in names


def read(skills_dir, name):
    p = os.path.join(skills_dir, name, 'SKILL.md')
    if not os.path.isfile(p):
        return None
    head = open(p, encoding='utf-8').read(4000)
    m = re.search(r'^---\s*$(.*?)^---\s*$', head, re.S | re.M)
    fm = m.group(1) if m else ''
    d = re.search(r'^description:\s*(.+?)\s*$', fm, re.M)
    desc = d.group(1).strip() if d else ''
    return re.sub(r'\s+', ' ', desc)


def build_text(cfg):
    s = dict(DEFAULT, **(cfg.get('skills') or {}))
    sdir = cfg.path(s['dir'])
    names = sorted(n for n in os.listdir(sdir) if os.path.isdir(os.path.join(sdir, n)))
    rel = s['dir'].rstrip('/')
    seen, out = set(), []
    for g in s['groups']:
        match = _matcher(g)
        rows = []
        for n in names:
            if n in seen or not match(n):
                continue
            desc = read(sdir, n)
            if desc is None:
                continue
            seen.add(n)
            rows.append((n, desc))
        if not rows:
            continue
        out.append(f'\n## {g["title"]}\n\n{g.get("note", "")}\n')
        out.append('| skill | what it is for |')
        out.append('|---|---|')
        for n, d in rows:
            short = d if len(d) <= 160 else d[:157].rsplit(' ', 1)[0] + '…'
            out.append(f'| [`{n}`]({rel}/{n}/SKILL.md) | {short} |')
    rest = [n for n in names if n not in seen and read(sdir, n) is not None]
    if rest:
        out.append(f'\n## Not grouped yet\n\n{s["ungrouped_note"]}\n')
        out.append('| skill | what it is for |')
        out.append('|---|---|')
        for n in rest:
            d = read(sdir, n)
            out.append(f'| [`{n}`]({rel}/{n}/SKILL.md) | {d if len(d) <= 160 else d[:157] + "…"} |')
    out.append('\n---\n' + s['footer'].format(n=len(seen) + len(rest)) + '\n')
    body = '\n'.join(out)
    head = open(cfg.path(s['preamble']), encoding='utf-8').read().rstrip() if s.get('preamble') else '# Skills'
    return head + '\n\n' + s['marker'] + '\n' + body, s


def main(argv, cfg):
    if not cfg.get('skills'):
        raise SystemExit('no skills map: add a "skills" section to aethern.json')
    text, s = build_text(cfg)
    outp = cfg.path(s['out'])
    name = os.path.basename(s['out'])
    if '--check' in argv:
        have = open(outp, encoding='utf-8').read() if os.path.exists(outp) else ''
        if have.strip() != text.strip():
            print(s['stale'].format(out=name))
            return 1
        print(f'  {name} is current ({text.count("| [`")} skills listed)')
        return 0
    open(outp, 'w', encoding='utf-8').write(text + '\n')
    print(f'wrote {name} — {text.count("| [`")} skills')
    return 0
