"""PROJECT MAP: one table of every system (what it does, its files, guide, command, status) plus the
data flow between them, so an agent asks for the one system it needs instead of reading the whole map.

Extracted from Paper Cinema's tools/build_systems.py (the builder) and generalised: the source file,
its markers and the connections come from aethern.json `catalog`. The query commands are new.

    aethern map build                  regenerate the JSON map from the Markdown table, check every file exists
    aethern map show SOUND [COMBAT]    one system: does, files (with line counts), guide, command, links in/out
    aethern map find camera shot       systems whose id, name, text or files match the words
    aethern map deps COMBAT [--up] [--depth 2]   what it feeds (or, --up, what feeds it)
    aethern map owner tools/ai.py      which systems list this file (as code or as guide)
    aethern map list                   every id and name, one line each
Add --json to any query for machine-readable output.

Source format: a Markdown table between `section_start` and `section_end`, one row per system:
| `ID` | **Name** | what it does | `files` | `guides` | `command` | status |
"""
import fnmatch
import json
import os
import re

STATUS = {'✅': 'built', '🧪': 'test', '📋': 'planned'}


def _cat(cfg):
    c = cfg.get('catalog')
    if not c:
        raise SystemExit('no project map: add a "catalog" section to aethern.json (see packages/aethern/README.md)')
    return c


# ---------------------------------------------------------------------- build
def parse(md, start='## The catalogue', end='Legend:', status=None):
    status = status or STATUS
    body = md.split(start)[1].split(end)[0] if start in md else md
    rows = [l for l in body.splitlines() if l.startswith('| `')]
    strip = lambda x: x.replace('**', '').strip()
    systems = []
    for l in rows:
        c = [x.strip() for x in l.strip('|').split('|')]
        systems.append({"id": c[0].strip('`'), "name": strip(c[1]), "does": strip(c[2]),
                        "files": re.findall(r'`([^`]+)`', c[3]), "guide": re.findall(r'`([^`]+)`', c[4]),
                        "command": (re.findall(r'`([^`]+)`', c[5]) or [None])[0],
                        "status": status.get(c[6][:1], c[6]), "status_note": c[6]})
    return systems


def build(cfg, out=print):
    c = _cat(cfg)
    md = open(cfg.path(c.get('source', 'SYSTEMS.md')), encoding='utf-8').read()
    systems = parse(md, c.get('section_start', '## The catalogue'), c.get('section_end', 'Legend:'), c.get('status'))
    connections = c.get('connections', [])
    ids = {s['id'] for s in systems}
    bad = [x for x in connections if x[0] not in ids or x[1] not in ids]
    missing = []
    for s in systems:
        for f in s['files'] + s['guide']:
            path = f.split('§')[0].strip()
            if any(ch in path for ch in '*<') or not path:
                continue
            if not os.path.exists(cfg.path(path)):
                missing.append(f"{s['id']}: {path}")
    doc = {"_about": c.get('about', 'Machine-readable catalogue of every system. Generated by aethern map build; connections = [from, to] data flow.'),
           "start_here": c.get('start_here', []), "golden_path": c.get('golden_path', []),
           "systems": systems, "connections": connections}
    with open(cfg.path(c.get('out', 'systems.json')), 'w', encoding='utf-8') as f:
        json.dump(doc, f, ensure_ascii=False, indent=1)
    out(f'{os.path.basename(c.get("out", "systems.json"))}: {len(systems)} systems, {len(connections)} connections')
    for m in missing:
        out(f'  missing file: {m}')
    for b in bad:
        out(f'  bad connection: {b}')
    return 1 if missing or bad else 0


# ---------------------------------------------------------------------- load (cached by mtime)
_LOADED = {}


def load(cfg):
    """The map, rebuilt in memory from the Markdown when the JSON is missing or older than it."""
    c = _cat(cfg)
    jp, mp = cfg.path(c.get('out', 'systems.json')), cfg.path(c.get('source', 'SYSTEMS.md'))
    stamp = (os.path.getmtime(jp) if os.path.exists(jp) else 0, os.path.getmtime(mp) if os.path.exists(mp) else 0)
    hit = _LOADED.get(jp)
    if hit and hit[0] == stamp:
        return hit[1]
    if os.path.exists(jp) and stamp[0] >= stamp[1]:
        doc = json.load(open(jp, encoding='utf-8'))
    else:
        md = open(mp, encoding='utf-8').read()
        doc = {'systems': parse(md, c.get('section_start', '## The catalogue'), c.get('section_end', 'Legend:'), c.get('status')),
               'connections': c.get('connections', [])}
    _LOADED[jp] = (stamp, doc)
    return doc


def _by_id(doc):
    return {s['id']: s for s in doc['systems']}


def _lines(cfg, rel):
    p = cfg.path(rel.split('§')[0].strip())
    if any(ch in rel for ch in '*<'):
        return 'glob'
    if os.path.isdir(p):
        return 'dir'
    if not os.path.isfile(p):
        return 'missing'
    try:
        with open(p, 'rb') as f:
            return sum(1 for _ in f)
    except Exception:
        return '?'


def show(cfg, ids, full=False):
    doc = load(cfg)
    by = _by_id(doc)
    res = []
    for i in ids:
        s = by.get(i.upper()) or by.get(i)
        if not s:
            near = [x for x in by if i.upper() in x]
            res.append({'id': i, 'error': 'unknown id', 'near': near[:8]})
            continue
        does = s['does'] if full or len(s['does']) <= 280 else s['does'][:277].rsplit(' ', 1)[0] + '…'
        res.append({'id': s['id'], 'name': s['name'], 'status': s['status'], 'does': does,
                    'files': {f: _lines(cfg, f) for f in s['files']}, 'guide': s['guide'], 'command': s['command'],
                    'from': [a for a, b in doc['connections'] if b == s['id']],
                    'to': [b for a, b in doc['connections'] if a == s['id']]})
    return res


def find(cfg, words, limit=8):
    doc = load(cfg)
    ws = [w.lower() for w in words if w]
    scored = []
    for s in doc['systems']:
        hay = {'id': s['id'].lower(), 'name': s['name'].lower(), 'does': s['does'].lower(),
               'files': ' '.join(s['files'] + s['guide']).lower()}
        score = sum(4 * (w in hay['id']) + 3 * (w in hay['name']) + 2 * (w in hay['files']) + (w in hay['does']) for w in ws)
        if score:
            scored.append((score, s))
    scored.sort(key=lambda x: -x[0])
    return [{'id': s['id'], 'name': s['name'], 'files': s['files'][:3]} for _, s in scored[:limit]]


def deps(cfg, sid, up=False, depth=1):
    doc = load(cfg)
    edges = doc['connections']
    seen, frontier, layers = {sid}, [sid], []
    for _ in range(max(1, depth)):
        nxt = []
        for n in frontier:
            for a, b in edges:
                src, dst = (b, a) if up else (a, b)
                if src == n and dst not in seen:
                    seen.add(dst)
                    nxt.append(dst)
        if not nxt:
            break
        layers.append(nxt)
        frontier = nxt
    return layers


def owner(cfg, rel):
    doc = load(cfg)
    rel = os.path.relpath(rel, cfg.root) if os.path.isabs(rel) else re.sub(r'^(\./)+', '', rel)
    hits = []
    for s in doc['systems']:
        for f in s['files'] + s['guide']:
            f0 = f.split('§')[0].strip()
            if f0 == rel or fnmatch.fnmatch(rel, f0) or (f0.endswith('/') and rel.startswith(f0)) \
                    or (f0.endswith('.*') and fnmatch.fnmatch(rel, f0)):
                hits.append(s['id'])
                break
    return hits


def answer(cfg, q):
    """One compact text answer for a free-form query: an id, a file path, or words. Used by the worker's map tool."""
    q = q.strip()
    if not q:
        return 'give an id (SOUND), a file (tools/ai.py) or words (camera shot)'
    try:
        by = _by_id(load(cfg))
    except SystemExit as e:
        return str(e)
    if q.upper() in by:
        return json.dumps(show(cfg, [q])[0], ensure_ascii=False)
    if '/' in q or os.path.exists(cfg.path(q)):
        return json.dumps({'file': q, 'systems': owner(cfg, q)})
    return json.dumps(find(cfg, q.split()), ensure_ascii=False)


# ---------------------------------------------------------------------- CLI
def main(argv, cfg):
    import argparse
    ap = argparse.ArgumentParser(prog='aethern map')
    ap.add_argument('cmd', choices=['build', 'show', 'find', 'deps', 'owner', 'list', 'ask'])
    ap.add_argument('args', nargs='*')
    ap.add_argument('--json', action='store_true')
    ap.add_argument('--full', action='store_true', help='show: do not shorten the description')
    ap.add_argument('--up', action='store_true', help='deps: what feeds it instead of what it feeds')
    ap.add_argument('--depth', type=int, default=1)
    a = ap.parse_args(argv)
    if a.cmd == 'build':
        return build(cfg)
    if a.cmd == 'ask':
        print(answer(cfg, ' '.join(a.args)))
        return 0
    if a.cmd == 'list':
        doc = load(cfg)
        rows = [(s['id'], s['name'], s['status']) for s in doc['systems']]
        if a.json:
            print(json.dumps(rows, ensure_ascii=False))
        else:
            for r in rows:
                print(f'{r[0]:12} {r[2]:8} {r[1]}')
        return 0
    if not a.args:
        raise SystemExit(f'aethern map {a.cmd} needs an argument')
    if a.cmd == 'show':
        res = show(cfg, a.args, full=a.full)
        if a.json:
            print(json.dumps(res, ensure_ascii=False))
        else:
            for s in res:
                if 'error' in s:
                    print(f'{s["id"]}: unknown id' + (f' (near: {", ".join(s["near"])})' if s['near'] else ''))
                    continue
                print(f'{s["id"]} · {s["name"]} · {s["status"]}\n  {s["does"]}')
                if s['files']:
                    print('  files: ' + ', '.join(f'{f} ({n})' for f, n in s['files'].items()))
                if s['guide']:
                    print('  guide: ' + ', '.join(s['guide']))
                if s['command']:
                    print(f'  run:   {s["command"]}')
                if s['from'] or s['to']:
                    print(f'  from:  {", ".join(s["from"]) or "-"}   to: {", ".join(s["to"]) or "-"}')
        return 0 if all('error' not in s for s in res) else 1
    if a.cmd == 'find':
        res = find(cfg, a.args)
        if a.json:
            print(json.dumps(res, ensure_ascii=False))
        else:
            for s in res:
                print(f'{s["id"]:12} {s["name"]}  [{", ".join(s["files"])}]')
            if not res:
                print('no system matches')
        return 0
    if a.cmd == 'deps':
        layers = deps(cfg, a.args[0].upper(), up=a.up, depth=a.depth)
        if a.json:
            print(json.dumps(layers))
        else:
            arrow = '←' if a.up else '→'
            for i, l in enumerate(layers, 1):
                print(f'{arrow * i} {", ".join(l)}')
            if not layers:
                print('no connections')
        return 0
    if a.cmd == 'owner':
        for p in a.args:
            hits = owner(cfg, p)
            print(json.dumps({'file': p, 'systems': hits}) if a.json else f'{p}: {", ".join(hits) or "no system lists it"}')
        return 0
